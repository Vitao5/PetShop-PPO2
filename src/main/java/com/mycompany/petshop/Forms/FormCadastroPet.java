    private void preencherCombo(){
        String nome = txtNomeCons.getText().trim();
        if(!nome.isEmpty()){
            lstPets = petBO.getPets(nome);
        }else{
            lstPets = petBO.getPets();
        }
        cmbPet.removeAllItems();
        if(lstPets != null){
            lstPets.forEach(itemPet -> {
                cmbPet.addItem(itemPet.getNome() + " | " + itemPet.getIdpet());
            });
        }
    }
    
    private void preencherCampos(Pet pet){
        txtIdPet.setText(String.valueOf(pet.getIdpet()));
        txtNome.setText(pet.getNome());
        txtDataNasc.setText(pet.getData_nascimento());
        txtRaca.setText(pet.getRaca());
        txtCor.setText(pet.getCor());
        txtPorte.setText(pet.getPorte());
        lstPessoas = new ArrayList<>();
        lstPessoas.add(pet.getPessoa());
        cmbPessoas.addItem(pet.getPessoa().getNome() + " | " + pet.getPessoa().getIdPessoa());
        btnSalvar.setEnabled(false);
    }
    
    private void preencherCampos(){
        if(lstPets != null && !lstPets.isEmpty()){
            int index = cmbPet.getSelectedIndex();
            if(index >= 0 && index < lstPets.size()){
                Pet pet = lstPets.get(index);
                preencherCampos(pet);
            }
        }
    }
    
    private void preencherComboPessoa(){
        String nome = txtNomePessoa.getText().trim();
        if(!nome.isEmpty()){
            lstPessoas = pBO.getPessoas(nome);
        }else{
            lstPessoas = pBO.getPessoas();
        }
        cmbPessoas.removeAllItems();
        if(lstPessoas != null){
            lstPessoas.forEach(itemPessoa -> {
                cmbPessoas.addItem(itemPessoa.getNome() + " | " + itemPessoa.getIdPessoa());
            });
        }
    }
    

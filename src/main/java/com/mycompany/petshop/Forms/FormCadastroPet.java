    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        // TODO add your handling code here:
        if(cmbPessoas.getSelectedIndex() < 0 || lstPessoas == null || lstPessoas.isEmpty()){
            JOptionPane.showMessageDialog(null, "Selecione o proprietário do pet.");
            return;
        }
        Pet pet = new Pet();
        pet.setNome(txtNome.getText());
        pet.setData_nascimento(txtDataNasc.getText());
        pet.setRaca(txtRaca.getText());
        pet.setCor(txtCor.getText());
        pet.setPorte(txtPorte.getText());
        pet.setPessoa(lstPessoas.get(cmbPessoas.getSelectedIndex()));

        petBO.salvar(pet);
        int codigo = pet.getIdpet();
        
        if(codigo != -1){
            txtIdPet.setText(String.valueOf(pet.getIdpet()));
            JOptionPane.showMessageDialog(null, "Dados salvos com sucesso!");
            btnSalvar.setEnabled(false);
            preencherCombo();
        }else{
            JOptionPane.showMessageDialog(null, "Erro ao salvar!");
        }
    }//GEN-LAST:event_btnSalvarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        // TODO add your handling code here:
        if(txtIdPet.getText().trim().isEmpty()){
            JOptionPane.showMessageDialog(null, "Selecione um pet para editar.");
            return;
        }
        if(cmbPessoas.getSelectedIndex() < 0 || lstPessoas == null || lstPessoas.isEmpty()){
            JOptionPane.showMessageDialog(null, "Selecione o proprietário do pet.");
            return;
        }
        Pet pet = new Pet();
        pet.setIdpet(Integer.parseInt(txtIdPet.getText()));
        pet.setNome(txtNome.getText());
        pet.setData_nascimento(txtDataNasc.getText());
        pet.setRaca(txtRaca.getText());
        pet.setCor(txtCor.getText());
        pet.setPorte(txtPorte.getText());
        pet.setPessoa(lstPessoas.get(cmbPessoas.getSelectedIndex()));

        petBO.editar(pet);
        JOptionPane.showMessageDialog(null, "Dados editados com sucesso!");
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        // TODO add your handling code here:
        if(txtIdPet.getText().trim().isEmpty()){
            JOptionPane.showMessageDialog(null, "Selecione um pet para excluir.");
            return;
        }
        Pet pet = new Pet();
        pet.setIdpet(Integer.parseInt(txtIdPet.getText()));
        int verif = petBO.excluir(pet);
        
        if(verif == 1){
            novo();
            JOptionPane.showMessageDialog(null, "Pet excluído com sucesso!");
        }else{
            JOptionPane.showMessageDialog(null, "Erro ao excluir!");
        }
    }//GEN-LAST:event_btnExcluirActionPerformed


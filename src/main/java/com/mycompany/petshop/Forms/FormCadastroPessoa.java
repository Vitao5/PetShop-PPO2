    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        // TODO add your handling code here:
        Pessoa pessoa = new Pessoa();
        pessoa.setNome(txtNome.getText());
        pessoa.setData(txtDataNasc.getText());
        
        pessoa = pBO.salvar(pessoa);
        
        int codigo = pessoa.getIdPessoa();
        if(codigo != -1){
            txtCodigo.setText(String.valueOf(pessoa.getIdPessoa()));
            JOptionPane.showMessageDialog(null, "Dados salvos com sucesso!");
            preencherCombo();
        }else{
            JOptionPane.showMessageDialog(null, "Erro ao salvar os dados.");
        }
    }//GEN-LAST:event_btnSalvarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        // TODO add your handling code here:
        if(txtCodigo.getText().trim().isEmpty()){
            JOptionPane.showMessageDialog(null, "Selecione uma pessoa para excluir.");
            return;
        }
        Pessoa pessoa = new Pessoa();
        pessoa.setIdPessoa(Integer.parseInt(txtCodigo.getText()));
        int verif = pBO.excluir(pessoa);
        
        if(verif == 1){
            novo();
            JOptionPane.showMessageDialog(null, "Dados excluídos com sucesso!");
        }else{
            JOptionPane.showMessageDialog(null, "Erro ao excluir os dados.");
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed
        // TODO add your handling code here:
        if(cmbPessoas.getItemCount() == 0 || cmbPessoas.getSelectedIndex() == -1){
            preencherCombo();
        }
        preencherCampos();
    }//GEN-LAST:event_btnConsultarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        // TODO add your handling code here:
        if(txtCodigo.getText().trim().isEmpty()){
            JOptionPane.showMessageDialog(null, "Selecione uma pessoa para editar.");
            return;
        }
        Pessoa pessoa = new Pessoa();
        pessoa.setIdPessoa(Integer.parseInt(txtCodigo.getText()));
        pessoa.setNome(txtNome.getText());
        pessoa.setData(txtDataNasc.getText());
        pBO.editar(pessoa);
        JOptionPane.showMessageDialog(null, "Dados editados com sucesso!");
    }//GEN-LAST:event_btnEditarActionPerformed


    private void preencherCombo(){
        String nome = txtConsNome.getText().trim();
        if(!nome.isEmpty()){
            lstPessoas = pBO.getPessoas(nome);
        }else{
            lstPessoas = pBO.getPessoas();
        }
        cmbPessoas.removeAllItems();
        if(lstPessoas != null){
            lstPessoas.forEach(itemPessoa -> {
                cmbPessoas.addItem(itemPessoa.getNome() + " | " + itemPessoa.getIdPessoa());
            });
        }
    }
    
    public void preencherCampos(){
        if(lstPessoas != null && !lstPessoas.isEmpty()){
            int index = cmbPessoas.getSelectedIndex();
            if(index >= 0 && index < lstPessoas.size()){
                Pessoa pessoa = lstPessoas.get(index);
                
                txtCodigo.setText(String.valueOf(pessoa.getIdPessoa()));
                txtNome.setText(pessoa.getNome());
                txtDataNasc.setText(pessoa.getData());
                btnSalvar.setEnabled(false);
            }
        }
    }
    
    public void novo(){
        txtConsNome.setText("");
        txtCodigo.setText("");
        txtNome.setText("");
        txtDataNasc.setText("");
        btnSalvar.setEnabled(true);
        preencherCombo();
    }


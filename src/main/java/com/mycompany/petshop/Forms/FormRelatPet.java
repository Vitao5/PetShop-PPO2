    private void pesquisar(){
        List<Pet> lstPets;

        String nome = txtNomeCons.getText().trim();
        String dataInicio = txtDataInicio.getText().trim();
        String dataFim = txtDataFim.getText().trim();

        boolean temNome = !nome.isEmpty();
        boolean temDatas = (dataInicio.length() == 10) && (dataFim.length() == 10);

        if (temNome && temDatas) {
            lstPets = petBO.getPets(nome, dataInicio, dataFim);
        } else if (temNome) {
            lstPets = petBO.getPets(nome);
        } else if (temDatas) {
            lstPets = petBO.getPets(dataInicio, dataFim);
        } else {
            lstPets = petBO.getPets();
        }
        preencherTabela(lstPets);
    }
    
    private void preencherTabela(List<Pet> lstPets){
        DefaultTableModel tabelaPets = (DefaultTableModel)
        tabPets.getModel();
        tabPets.getColumnModel().getColumn(0).setPreferredWidth(180);

        tabPets.getColumnModel().getColumn(1).setPreferredWidth(60);
        tabPets.getColumnModel().getColumn(2).setPreferredWidth(60);

        tabPets.getColumnModel().getColumn(3).setPreferredWidth(60);
        tabPets.getColumnModel().getColumn(4).setPreferredWidth(60);
        tabPets.getColumnModel().getColumn(5).setPreferredWidth(180);

        tabelaPets.setNumRows(0);

        lstPets.forEach(itemPet -> {
            String nomeDono = (itemPet.getPessoa() != null && itemPet.getPessoa().getNome() != null) ? itemPet.getPessoa().getNome() : "";
            tabelaPets.addRow(new Object[]{itemPet.getNome(),
                itemPet.getRaca(), itemPet.getPorte(), itemPet.getCor(),
                itemPet.getData_nascimento(), nomeDono});
        });
    }
    
    
